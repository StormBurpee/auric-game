/**
 * Tile pixels — one 16x16 grid per TileKey in world/tiles.ts, GBC
 * discipline. Tiles blit with opaqueZero, so '.' is the LIGHTEST ground
 * colour of the tile's palette, rising to 3 at the darkest. WATER and
 * FLOWER breathe with two frames; everything else holds still.
 *
 * Seam rules honoured throughout: full-width features (roof laps, wall
 * timbers, ledge faces, fence rails) run edge to edge; interior features
 * (pebbles, blooms, boulders) keep clear of the rim; TREE canopy reaches
 * both side edges on its middle rows so adjacent trees read as one
 * continuous canopy.
 */
