/**
 * The people of Ambervale — 16x16 two-frame walkers, GB body plan: big
 * head (7-8px), small body, short legs. Palette slots: 1 skin/highlight,
 * 2 signature colour, 3 outline/hair/dark. `side` faces LEFT; the engine
 * mirrors it for rightward walks, and mirrors the step frame of down/up
 * for the alternating stride, so step frames are drawn with the LEFT
 * (viewer's) leg lifted. Walk bob is 1px: step frames carry the body one
 * row lower. Skirted characters bounce whole-body and let the hem hide
 * the stride, the way the classics cheated it.
 */
