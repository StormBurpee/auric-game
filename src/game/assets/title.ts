/** Stamp hand-drawn parts onto one sheet (0 stays transparent). */
function compose(
  w: number,
  h: number,
  parts: ReadonlyArray<{ s: Sprite; x: number; y: number }>,
): Sprite {
  const px = new Uint8Array(w * h)
  for (const { s, x, y } of parts) {
    for (let sy = 0; sy < s.h; sy++) {
      for (let sx = 0; sx < s.w; sx++) {
        const v = s.px[sy * s.w + sx]!
        if (v !== 0) px[(y + sy) * w + (x + sx)] = v
      }
    }
  }
  return { w, h, px }
}

